async function clearSelection(page: Page) {
  const canvas = page.getByRole('region', { name: '流程画布', exact: true })
  const box = await canvas.boundingBox()
  if (!box) throw new Error('画布未显示')
  await canvas.click({ position: { x: 26, y: box.height - 120 } })
}

